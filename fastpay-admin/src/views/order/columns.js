/**
 * Fast 易支付 - 订单列表的列宽方案（单位 px）
 *
 * 这几个数字不是随手填的。整张表所有列加起来必须放得进 1280 宽窗口里的表格区域，
 * 否则表格会横向滚动，而右侧固定的「操作」列会浮在内容上方，把「创建时间」盖掉半截
 * （线上就是这么坏的：只看得见 "2026-08…"）。
 *
 * 1280 窗口下表格能用的宽度：
 *   1280 - 220(侧边栏) - 40(内容区左右内边距) - 40(卡片左右内边距) - 6(纵向滚动条) = 974
 *
 * 下面每个基准宽的定法：**把列宽改成候选值，在 Chromium 里真渲染一遍，看内容折不折行、
 * 截不截断、表头折不折行**，取"刚好都正常"的那一档再留一点余量。不要靠「量一下文字宽度
 * 再加个内边距」来推算——那样算出来的数会偏小，MTM-168 就是这么把金额列少给了 10px。
 *
 * 每一列的下限也别拿手头那一条测试数据当上限。金额、商户名、通知次数这些
 * 长度都是变的，要按"业务上可能出现的最长内容"定。
 *
 * 改列宽之前先看一眼 test/OrderList.spec.js 里那几条约束。
 */
export const ORDER_COLUMN_WIDTHS = {
  // 平台订单号是 FP + 20 位数字，一行必须完整显示（管理员要拿它去对账）。
  // 实测 187 刚好放得下，再少一格就被截，这一列不许再压。
  orderNo: 187,
  // 商户名长度没有上限，1280 下怎么都放不全，只能截断 + 悬停看全名。
  // 这里给的是"最低保障"，窗口一宽就会自动变宽，见 resolveColumnWidths()。
  // 整张表的预算不够时也是先削这一列——它本来就是截断显示的，少几个字影响最小。
  merchant: 93,
  // 金额位数没有上限，列宽要按"业务上可能出现的最大金额"定，不能按手头那条测试数据定。
  // 实测（真渲染，看折不折行）：¥12800.00 要 88、¥99999.99 要 92+、¥128000.00 要 96+、
  // ¥888888.88 要 98。所以给 98 —— 百万级金额都能一行显示完。
  // 千万级（¥9999999.99，要 108）仍会折成两行：那超出这个平台（个人收款码免签）的实际量级，
  // 为它再占 10px 不值得。折行不是截断，金额的每一位数字始终看得见。
  amount: 98,
  // 下面三列装的是短标签（微信 / 已支付 / 成功）。宽度下限不是标签本身，
  // 是四个字的表头「支付类型」「回调状态」——实测 80，再窄表头就折行了，比内容更早出问题。
  payType: 80,
  status: 76,
  // 这一列除了标签还有一行副文案。MTM-193 之前写的是「已通知 N 次」，实测要 92px，
  // 次数一上两位数就折成两行；现在改成最短的「通知N次」，实测 75px，80 装得下了。
  // 别再往下压：80 是**表头**「回调状态」的下限，跟副行无关，压到 75 换成表头折行。
  // 也就是说这一列没有可以匀给别的列的余量，副行省下来的 17px 是被表头吃掉的。
  notify: 80,
  // 时间拆成「2026-08-19」「10:30:00」上下两行，且是 nowrap —— 宽度不够不会折行，
  // 会直接被截掉尾巴（就是 MTM-165 那个"只看得见 2026-08…"的老毛病）。实测下限 96，给 100 留 4px 余量。
  createTime: 100,
  payTime: 100,
  // 待支付的订单有「详情 / 确认支付 / 关闭」三个按钮，实测 154 才排得下一行，160 留 6px 余量
  action: 160
}

/**
 * 两列"越宽越好"的列各自的封顶宽度。到了这个宽度，这一列的内容就全能一行显示完了，
 * 再宽只是浪费——原来的毛病就出在这儿：订单号列吃掉了大部分富余宽度，
 * 右边空一大片，商户名却还在截断。
 */
/**
 * 实测下限：每种内容要"一行完整显示"，这一列最少得多宽。
 *
 * 全部是在 Chromium 里把列宽逐档调窄、真渲染出来看折不折行 / 截不截断量到的，
 * 不是拿文字宽度加内边距算的。测试拿它当断言基准，改列宽时一眼能看出还剩多少余量。
 */
export const MEASURED_MIN_WIDTHS = {
  /** FP + 20 位平台订单号，一行完整显示 */
  orderNo: 187,
  /** ¥888888.88，百万级金额一行显示不折行 */
  amountMillion: 98,
  /** ¥9999999.99，千万级金额；超出本平台实际量级，当前没给到 */
  amountTenMillion: 108,
  /** 四个字的表头「支付类型」「回调状态」不折行 */
  fourCharHeader: 80,
  /**
   * 回调状态列副行、三位数次数（NOTIFY_COUNT_SAMPLE）一行显示完。
   * 改文案就得重新实测这个数：「已通知 999 次」是 92（放不进 80，MTM-193 修的就是它），
   * 「通知999次」是 75。
   */
  notifyCountLine: 75,
  /** 「2026-08-19」「10:30:00」两行都不被截 */
  time: 96,
  /** 待支付订单的「详情 / 确认支付 / 关闭」三个按钮排一行 */
  action: 154
}

/**
 * 订单列表「回调状态」列副行的文案：通知了几次。
 *
 * 写在列宽文件里，是因为这句话的长度直接决定这一列够不够用——列宽给死了 80px
 * （下限是表头「回调状态」，压不下去），文案只能迁就列宽。想改文案的人在这里
 * 就能看见约束：改完必须重新实测宽度、同步更新 MEASURED_MIN_WIDTHS.notifyCountLine。
 *
 * 详情弹窗里是宽松的两栏布局，仍然用完整的「已通知 3 次」（见 utils/orderDetail.js）。
 * 两处写法不同是有意的：列表是密集扫读，越短越好；详情是逐条细看，完整更好读。
 *
 * @param {number} count 已尝试通知的次数
 * @returns {string} 例如「通知12次」
 */
export function formatNotifyCount(count) {
  return `通知${count}次`
}

/**
 * 实测列宽用的最长样本。三位数是这一列的设计上限：自动重试到 5 次就停
 * （后端 notifyCount < 5），只有管理员一次次手点「重发通知」才可能往上堆。
 */
export const NOTIFY_COUNT_SAMPLE = formatNotifyCount(999)

export const ORDER_COLUMN_CAPS = {
  // 副行「商户单号 SHOP-ORDER-20260819-000001」实测 231px，231 + 24 = 255
  orderNo: 255,
  // 16 个汉字的公司全名（如「广州天河智汇网络科技有限责任公司」）实测 224px，224 + 24 = 248
  merchant: 248
}

/**
 * 富余宽度的发放顺序。谁排前面谁先吃饱，每一档都写清楚吃饱了能看到什么。
 *
 * 为什么商户名排在订单号前面：基准宽 187 已经保证了平台订单号（管理员对账用的那串）
 * 一行显示完整，这条硬要求在最窄的 1280 下就已经满足了；订单号列再宽只是让副行的
 * 「商户单号」也能一行放下——那是次要信息，而且商户单号长度没有上限，本来就得靠截断
 * 加悬停。所以先给商户名补到"常见公司全名能看全"，再回头喂订单号的副行。
 */
const SPARE_WIDTH_PLAN = [
  // 「深圳大冰熊科技有限公司」这类 11 个字的公司名：11 × 14 + 24 = 178
  { key: 'merchant', upTo: 178 },
  // 订单号列副行的「商户单号 SHOP-ORDER-20260819-000001」完整显示
  { key: 'orderNo', upTo: ORDER_COLUMN_CAPS.orderNo },
  // 还有富余，商户名继续放宽到 16 个字的公司全名
  { key: 'merchant', upTo: ORDER_COLUMN_CAPS.merchant }
]

/** 1280 宽窗口下，表格实际能用的宽度 */
export const TABLE_WIDTH_AT_1280 = 1280 - 220 - 40 - 40 - 6

/** 所有列的最小总宽 */
export function totalColumnWidth(widths = ORDER_COLUMN_WIDTHS) {
  return Object.values(widths).reduce((sum, width) => sum + width, 0)
}

/**
 * 按表格实际可用宽度分配列宽。
 *
 * 每列先拿基准宽（总和刚好等于 1280 能给的 974，这时候订单号完整、商户名截断），
 * 窗口再宽出来的部分按 SPARE_WIDTH_PLAN 一档一档发放，两列都吃饱之后剩下的对半分，
 * 免得表格右边留一条空白。
 *
 * 之前是把富余宽度按 min-width 比例分给这两列（Element Plus 的默认行为），
 * 结果 1440 下订单号列拿到 288px、右边空出五十多像素没人用，
 * 商户名却只有 168px，「深圳大冰熊科技有限公司」还是被截成「深圳大冰熊科技有…」。
 *
 * @param {number} tableWidth 表格容器的实际像素宽度
 * @returns {typeof ORDER_COLUMN_WIDTHS} 这个宽度下每一列应该多宽
 */
export function resolveColumnWidths(tableWidth) {
  const widths = { ...ORDER_COLUMN_WIDTHS }
  let spare = Math.max(0, Math.floor(tableWidth || 0) - totalColumnWidth())

  for (const { key, upTo } of SPARE_WIDTH_PLAN) {
    if (spare <= 0) break
    const got = Math.min(spare, Math.max(0, upTo - widths[key]))
    widths[key] += got
    spare -= got
  }

  if (spare > 0) {
    const half = Math.floor(spare / 2)
    widths.orderNo += half
    widths.merchant += spare - half
  }

  return widths
}
