-- Fast 易支付 数据库迁移脚本 V1.3（MySQL / MariaDB）—— 订单回调结果落库
-- 说明：老库升级用。新库直接执行 init.sql 就是新结构，不需要跑这里。
--
-- 为什么编号是 V1.3 不是 V1.2：
--   本脚本开发时主干上还没有 V1.2，合并主干时才发现 V1.2 已经被「密码存法换 bcrypt」
--   占用（随 v1.4.0 发布）。同一个编号有两份不同的脚本，操作的人会不知道该跑哪个、
--   先跑哪个，所以合并时统一顺延到 V1.3。
--   （补充：主干上还有另一份未发布的「pay_amount 撞单」脚本，最初也占了 V1.2，跟 v1.4.0
--   发出去的 V1.2 撞了。MTM-205 上把那份顺延成 V1.4，本脚本编号不变。）
--   执行顺序：V1.1 → V1.2 → V1.3 → V1.4，四个脚本互相无强依赖，先跑谁都不会破对方结构。
-- 变更点：
--   1. fp_pay_order 新增 notify_result 列 —— 存商户回调最近一次返回的内容（截断到 1000 字符）
--   2. fp_pay_order 新增 notify_error 列  —— 存商户回调最近一次的报错信息（超时/连不上/格式错等）
--
-- 为什么这么做：
--   现在回调成功失败都只写日志，运营在后台点开订单只看得到「回调失败」四个字，看不到为什么失败。
--   落库之后，管理后台和商户中心的订单详情就能直接看到失败原因，不用再去翻服务器日志。
--
-- 生产库怎么跑（顺序不能反：先跑本脚本，再部署新版 jar、重启后端）：
--   mysql -h <host> -P 3306 -u <user> -p bigbear_fastpay < V1_3__order_notify_result_mysql.sql
--   反过来做（先上新 jar 再跑脚本），中间那段时间订单接口会全挂，报「字段不存在」。
--
-- 注意：本项目当前生产环境跑的是 PostgreSQL，MySQL 版仅为老装机或本地 MySQL 部署预留。
--
-- 怎么回退：见文件末尾的「回退脚本」注释块。**先看那里的说明再动手。**
-- =====================================================

-- 新增：商户回调返回内容（截断到 1000 字符；商户回调可能返回长报错页面，避免撑爆行）
--
-- ⚠️ 关于下面这句 IF NOT EXISTS：
--   MariaDB 支持 `ADD COLUMN IF NOT EXISTS`（10.0.2 起），本脚本在 MariaDB 11.4 上实测通过。
--   **原厂 MySQL 不支持** —— MySQL 8.4 官方手册的 ALTER TABLE 语法里，ADD [COLUMN] 只有
--   `col_name column_definition [FIRST | AFTER col_name]` 和括号批量两种写法，没有 IF NOT EXISTS。
--   所以在原厂 MySQL 上跑会直接语法报错（ERROR 1064）。
--   在原厂 MySQL 上执行时：把两句里的 `IF NOT EXISTS` 去掉再跑；重复执行会报「列已存在」，属正常。
ALTER TABLE fp_pay_order
    ADD COLUMN IF NOT EXISTS notify_result VARCHAR(1000) DEFAULT NULL COMMENT '最近一次回调商户返回的内容（截断到 1000 字符）';

-- 新增：商户回调错误信息（异常类名 + message，截断到 500 字符）
ALTER TABLE fp_pay_order
    ADD COLUMN IF NOT EXISTS notify_error VARCHAR(500) DEFAULT NULL COMMENT '最近一次回调失败的错误信息（超时/连不上/格式错等）';

